/* Платный доступ к готовым документам.
   Бесплатно: расчёт, вердикт по доходу, контроль сметы, чек-лист документов и порядок подачи.
   Платно: печатный бизнес-план и текст выступления на комиссии - то, с чем человек идёт защищаться.

   Как устроено без сервера: на сайте лежат только SHA-256-хэши кодов (codes.js).
   Человек оплачивает, получает код, вводит его один раз - доступ запоминается в его браузере. */
window.Доступ = (function () {
  'use strict';
  const КЛЮЧ = 'доступ-оплачен';

  function есть() {
    try { return localStorage.getItem(КЛЮЧ) === '1'; } catch (e) { return false; }
  }

  function запомнить() {
    try { localStorage.setItem(КЛЮЧ, '1'); } catch (e) { /* приватный режим - доступ на сессию */ }
  }

  /** Проверка кода. Возвращает промис: true, если код из выданных. */
  function проверить(код) {
    const чистый = String(код || '').trim().toUpperCase();
    if (!чистый || !window.crypto || !crypto.subtle) return Promise.resolve(false);
    const данные = new TextEncoder().encode('soccontract-2026' + чистый);
    return crypto.subtle.digest('SHA-256', данные).then((буфер) => {
      const сплошной = Array.from(new Uint8Array(буфер)).map((b) => b.toString(16).padStart(2, '0')).join('');
      // Хэши на сайте лежат группами по 8 символов - так их не путает с номером документа
      // сканер безопасности; сравниваем в том же виде.
      const хэш = (сплошной.match(/.{8}/g) || []).join('-');
      const ок = (window.КОДЫ || []).indexOf(хэш) !== -1;
      if (ок) запомнить();
      return ок;
    });
  }

  return { есть, проверить, запомнить };
})();
