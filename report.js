/* Сборка печатных документов: бизнес-план, речь защиты, чек-лист, маршрут.
   Всё формируется в браузере посетителя - никакие данные никуда не отправляются. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.Документы = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const руб = (x) => (Math.round(Number(x) || 0)).toLocaleString('ru-RU') + ' ₽';
  const чис = (x) => (Math.round((Number(x) || 0) * 10) / 10).toLocaleString('ru-RU');
  const esc = (s) => String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

  const МЕСЯЦЫ = ['1-й', '2-й', '3-й', '4-й', '5-й', '6-й', '7-й', '8-й', '9-й', '10-й', '11-й', '12-й'];
  const ИМЕНА_КАТЕГОРИЙ = {
    основные: 'Оборудование и основные средства',
    запасы: 'Сырьё, материалы, товарные запасы',
    аренда: 'Аренда и имущественные обязательства',
    продвижение: 'Продвижение и реклама',
    разрешения: 'Разрешительные документы, ПО, электронная подпись'
  };

  /** Печатный бизнес-план. с - состояние формы, р - результаты расчёта. */
  function бизнесПлан(с, р) {
    const сегодня = new Date().toLocaleDateString('ru-RU');
    const ф = р.финмодель;
    const см = р.смета;
    const строкиСметы = см.строки.map((x) => (
      '<tr><td>' + esc(x.название || ИМЕНА_КАТЕГОРИЙ[x.категория] || '') + '</td>' +
      '<td class="c">' + esc(ИМЕНА_КАТЕГОРИЙ[x.категория] || x.категория) + '</td>' +
      '<td class="r">' + руб(x.сумма) + '</td></tr>'
    )).join('');

    const строкиМесяцев = ф.месяцы.map((м) => (
      '<tr><td>' + МЕСЯЦЫ[м.месяц - 1] + '</td>' +
      '<td class="r">' + чис(м.штук) + '</td>' +
      '<td class="r">' + руб(м.выручка) + '</td>' +
      '<td class="r">' + руб(м.переменные + м.постоянные) + '</td>' +
      '<td class="r">' + руб(м.налог) + '</td>' +
      '<td class="r"><b>' + руб(м.прибыль) + '</b></td></tr>'
    )).join('');

    const окуп = ф.окупаемостьМес
      ? ('Вложения окупаются на ' + ф.окупаемостьМес + '-м месяце работы.')
      : 'За первые 12 месяцев вложения полностью не окупаются, выход на возврат вложений планируется на втором году.';

    return '' +
      '<article class="doc">' +
      '<h1>Бизнес-план</h1>' +
      '<p class="sub">для получения государственной социальной помощи на основании социального контракта' +
      ' по направлению «осуществление индивидуальной предпринимательской деятельности»<br>' +
      esc(с.регион || '') + ', ' + сегодня + '</p>' +

      '<h2>1. Суть проекта</h2>' +
      '<p><b>Вид деятельности:</b> ' + esc(с.видДеятельности) + (с.оквэд ? ' (ОКВЭД ' + esc(с.оквэд) + ')' : '') + '.<br>' +
      '<b>Форма ведения деятельности:</b> ' + esc(с.формаДеятельности) + '.<br>' +
      '<b>Место ведения деятельности:</b> ' + esc(с.местоДеятельности || 'по месту жительства заявителя') + '.<br>' +
      '<b>Запрашиваемая сумма:</b> ' + руб(см.итого) + '.</p>' +
      '<p>' + esc(с.описание) + '</p>' +

      '<h2>2. Почему это будет востребовано</h2>' +
      '<p><b>Клиенты:</b> ' + esc(с.клиенты) + '</p>' +
      '<p><b>Конкуренты и чем отличаемся:</b> ' + esc(с.конкуренты) + '</p>' +
      '<p><b>Опыт и подготовка заявителя:</b> ' + esc(с.опыт) + '</p>' +

      '<h2>3. Смета расходов средств социального контракта</h2>' +
      '<table><thead><tr><th>Наименование</th><th>Статья расходов</th><th class="r">Сумма</th></tr></thead>' +
      '<tbody>' + строкиСметы +
      '<tr class="total"><td colspan="2">Итого</td><td class="r">' + руб(см.итого) + '</td></tr></tbody></table>' +
      '<p class="note">Доли расходов соответствуют пункту 10 подпункта «б» Правил, утверждённых постановлением ' +
      'Правительства Российской Федерации от 16.11.2023 № 1931 (в редакции от 29.12.2025): от размера денежной ' +
      'выплаты не более 10 % - на приобретение разрешительной документации, программного обеспечения и ' +
      'электронной подписи, не более 15 % - на принятие имущественных обязательств, не более 5 % - на размещение ' +
      'и продвижение продукции на торговых площадках, в сервисах объявлений и социальных сетях.</p>' +

      '<h2>4. Расчёт доходов и расходов на 12 месяцев</h2>' +
      '<p>Средняя цена: ' + руб(с.цена) + ' за ' + esc(с.единица) + '. Планируемый объём на полной загрузке: ' +
      чис(с.клиентовВМесяц) + ' в месяц, выход на полную загрузку - ' + с.выходНаМощность + ' мес. ' +
      'Налоговый режим: ' + esc(с.режимНазвание) + '.</p>' +
      '<table><thead><tr><th>Месяц</th><th class="r">Объём</th><th class="r">Выручка</th>' +
      '<th class="r">Расходы</th><th class="r">Налог</th><th class="r">Прибыль</th></tr></thead>' +
      '<tbody>' + строкиМесяцев +
      '<tr class="total"><td>За год</td><td class="r">&mdash;</td><td class="r">' + руб(ф.год.выручка) + '</td>' +
      '<td class="r">' + руб(ф.год.переменные + ф.год.постоянные) + '</td>' +
      '<td class="r">' + руб(ф.год.налог) + '</td><td class="r">' + руб(ф.год.прибыль) + '</td></tr></tbody></table>' +
      '<p>' + окуп + ' Рентабельность на полной загрузке - ' + чис(ф.маржаНаМощности) + ' %.' +
      (ф.точкаБезубыточности ? ' Точка безубыточности - ' + ф.точкаБезубыточности + ' ' + esc(с.единица) + ' в месяц.' : '') + '</p>' +

      '<h2>5. Ожидаемые результаты</h2>' +
      '<ul>' +
      '<li>Регистрация в качестве ' + esc(с.формаДеятельности) + ' и ведение деятельности в течение всего срока социального контракта (не более 12 месяцев).</li>' +
      '<li>Выход на ежемесячный доход от деятельности около ' + руб(ф.месяцы[11].прибыль) + ' к концу первого года.</li>' +
      '<li>Превышение среднедушевого дохода семьи над величиной прожиточного минимума и выход из категории малоимущих.</li>' +
      '<li>Ежемесячное подтверждение деятельности и ежеквартальное подтверждение дохода в орган социальной защиты, ' +
      'в том числе в период мониторинга, который орган проводит в течение 12 месяцев со дня окончания контракта.</li>' +
      '</ul>' +
      '<p class="sign">Заявитель: ______________________ / ______________________</p>' +
      '</article>';
  }

  /** Текст устного выступления на комиссии. */
  function речьЗащиты(с, р) {
    const ф = р.финмодель;
    const см = р.смета;
    const вопросы = (с.вопросыНиши || []).map((в) => '<li><b>' + esc(в) + '</b></li>').join('');
    return '' +
      '<article class="doc">' +
      '<h1>Что сказать на комиссии</h1>' +
      '<p class="sub">Выступление занимает 2-3 минуты. Говорите своими словами, цифры держите перед глазами.</p>' +
      '<h2>Короткое выступление</h2>' +
      '<blockquote>' +
      '<p>Здравствуйте. Я прошу социальный контракт на ' + esc(с.видДеятельности.toLowerCase()) + '. ' +
      'Планирую работать как ' + esc(с.формаДеятельности) + ' ' + esc(с.местоДеятельности ? ('по адресу: ' + с.местоДеятельности) : 'по месту жительства') + '.</p>' +
      '<p>' + esc(с.опыт) + '</p>' +
      '<p>Мои клиенты - ' + esc(с.клиенты.toLowerCase()) + '. ' + esc(с.конкуренты) + '</p>' +
      '<p>Прошу ' + руб(см.итого) + '. Основное - ' +
      esc((см.строки[0] && см.строки[0].название) || 'оборудование') + ', без этого работать нельзя. ' +
      'Доли по аренде, продвижению и оформлению уложены в пределы, установленные Правилами.</p>' +
      '<p>Считаю так: ' + руб(с.цена) + ' за ' + esc(с.единица) + ', ' + чис(с.клиентовВМесяц) +
      ' в месяц на полной загрузке. Выхожу на неё за ' + с.выходНаМощность + ' месяца. ' +
      'Это ' + руб(ф.месяцы[11].выручка) + ' выручки и около ' + руб(ф.месяцы[11].прибыль) + ' чистыми в месяц. ' +
      (ф.окупаемостьМес ? 'Вложения окупаются на ' + ф.окупаемостьМес + '-м месяце.' : 'Вложения окупаются на втором году работы.') + '</p>' +
      '<p>Обязуюсь тратить средства строго по смете, сохранять все чеки и договоры, вести деятельность весь срок контракта ' +
      'и ещё 12 месяцев после него, ежемесячно подтверждать регистрацию и ежеквартально - доход.</p>' +
      '</blockquote>' +
      '<h2>Вопросы, которые вам почти наверняка зададут</h2>' +
      '<ul class="qa">' +
      '<li><b>Почему именно эта сумма?</b> Ответ - по смете, построчно, с ценами конкретных поставщиков.</li>' +
      '<li><b>Откуда возьмутся клиенты?</b> Ответ - конкретные каналы: что уже есть, кто уже обращался.</li>' +
      '<li><b>Что будете делать, если доход окажется ниже плана?</b> Ответ - расширю услуги или каналы, деятельность не прекращу.</li>' +
      '<li><b>Есть ли опыт и обучение?</b> Ответ - назвать курсы, стаж, сертификаты.</li>' +
      '<li><b>Как будете отчитываться?</b> Ответ - чеки и договоры по каждой покупке, чеки НПД по доходам.</li>' +
      вопросы +
      '</ul>' +
      '<h2>Чего говорить не нужно</h2>' +
      '<ul>' +
      '<li>«Куплю что-нибудь на эти деньги, разберусь по ходу» - это прямой отказ.</li>' +
      '<li>«Подработка у меня уже есть, но нигде не оформлена» - см. раздел про уголовную ответственность.</li>' +
      '<li>Завышенные обещания прибыли: комиссия видит сотни планов и чувствует нарисованные цифры.</li>' +
      '</ul>' +
      '</article>';
  }

  /** Чек-лист документов и маршрут подачи. */
  function документы(с) {
    return '' +
      '<article class="doc">' +
      '<h1>Документы и порядок действий</h1>' +
      '<p class="sub">Точный перечень устанавливает регион, но этот состав спрашивают везде. ' +
      'Проверьте его на портале Госуслуг при подаче заявления - там список формируется под вашу ситуацию.</p>' +
      '<h2>Что собрать</h2>' +
      '<ol class="check">' +
      '<li>Паспорт заявителя и всех совершеннолетних членов семьи.</li>' +
      '<li>СНИЛС и ИНН членов семьи.</li>' +
      '<li>Свидетельства о рождении детей, о браке или о расторжении брака.</li>' +
      '<li>Сведения о доходах всех членов семьи за 3 месяца, предшествующих месяцу обращения: справки о зарплате, пособиях, пенсии, алиментах, доходах от самозанятости.</li>' +
      '<li>Документы об уважительных причинах отсутствия дохода, если доходов нет: справка из центра занятости, справка об уходе, больничные, справка об учёбе.</li>' +
      '<li>Реквизиты счёта в банке на имя заявителя.</li>' +
      '<li><b>Бизнес-план со сметой</b> - его вы печатаете здесь.</li>' +
      '<li>Документы на место ведения деятельности: договор аренды, согласие собственника, документ о праве на помещение или участок.</li>' +
      '<li>Документы об образовании, курсах, сертификатах по профилю - если есть.</li>' +
      '<li>Согласие на обработку персональных данных (бланк выдадут при подаче).</li>' +
      '</ol>' +
      '<h2>Порядок действий</h2>' +
      '<ol class="steps-doc">' +
      '<li><b>Подать заявление</b> - через Госуслуги (услуга «Назначение государственной социальной помощи на основании социального контракта»), МФЦ или отдел социальной защиты по месту жительства.</li>' +
      '<li><b>Пройти тестирование предпринимательских компетенций</b> (п. 36 Правил). Его проводят до комиссии. Не прошли - направят на бесплатное обучение не менее 16 академических часов; без сертификата об обучении в помощи откажут или предложат сменить направление. Отказ от тестирования - самостоятельное основание для отказа.</li>' +
      '<li><b>Защитить бизнес-план на межведомственной комиссии.</b> Могут вернуть план на доработку - это нормально, срок решения при этом продлевается.</li>' +
      '<li><b>Получить решение</b> - 10 рабочих дней со дня регистрации заявления (п. 28 Правил). Срок продлевается ' +
      'ещё до 20 рабочих дней, если нужны дополнительная проверка условий жизни семьи или сведения по ' +
      'межведомственным запросам. Если документы нужно доработать, рассмотрение приостанавливают не более чем ' +
      'на 5 рабочих дней (п. 30 Правил).</li>' +
      '<li><b>Зарегистрироваться как самозанятый или ИП</b> - это можно делать уже после одобрения; выплату переведут только после подтверждения регистрации.</li>' +
      '<li><b>Получить деньги</b> - единовременно или по этапам, как записано в вашем бизнес-плане и социальном контракте.</li>' +
      '<li><b>Отчитаться по расходам</b> - документами на каждую покупку, в сроки, указанные в контракте.</li>' +
      '<li><b>Вести деятельность</b> весь срок контракта (не более 12 месяцев). Ежемесячно подтверждается факт ' +
      'регистрации, ежеквартально - доход. После окончания контракта орган ещё 12 месяцев проводит мониторинг.</li>' +
      '</ol>' +
      '<h2>Когда откажут (основания из п. 25-27 Правил)</h2>' +
      '<ul>' +
      '<li>Среднедушевой доход семьи не ниже прожиточного минимума в регионе (кроме случаев, когда доход не оценивается).</li>' +
      '<li>Недостоверные или неполные сведения о доходах и составе семьи.</li>' +
      '<li><b>Бизнес-план не одобрен межведомственной комиссией</b> - самое частое основание на практике.</li>' +
      '<li>Отказ от тестирования предпринимательских компетенций либо отсутствие сертификата об обучении.</li>' +
      '<li>Действующий социальный контракт у заявителя или у члена его семьи.</li>' +
      '<li>Заявление подано в период мониторинга по прежнему контракту.</li>' +
      '<li>Непогашенная задолженность перед органом соцзащиты по прежнему контракту.</li>' +
      '<li>В течение 12 месяцев до обращения получена единовременная финансовая помощь на открытие дела от службы занятости.</li>' +
      '<li>Регистрация в качестве ИП или самозанятого не в том субъекте, где подано заявление.</li>' +
      '<li>У субъекта нет бюджетных ассигнований на эти цели в текущем году.</li>' +
      '</ul>' +
      '<h2>Если деятельность придётся прекратить</h2>' +
      '<p>Об обстоятельствах, из-за которых условия контракта больше не выполняются, нужно уведомить орган ' +
      'социальной защиты в течение 5 рабочих дней, а вернуть средства - в течение 30 календарных дней. ' +
      'Молчание в этой ситуации - самый частый путь к уголовному делу по статье 159.2 УК РФ.</p>' +
      '</article>';
  }

  return { бизнесПлан, речьЗащиты, документы, руб, чис, ИМЕНА_КАТЕГОРИЙ };
});
