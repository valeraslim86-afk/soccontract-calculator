/* Связь с внешним миром. Три канала, все - только по явному действию человека:
   1) заявка на платную услугу, 2) сообщение «в данных региона ошибка», 3) обезличенная статистика.
   Персональные данные калькулятор НЕ собирает и НЕ отправляет: расчёт целиком в браузере. */
window.НАСТРОЙКИ = {
  // Адрес обработчика Cloudflare Worker. Пока пусто - работает запасной путь (Telegram).
  endpoint: '',
  телеграм: 'pyankov_vv',
  цена: 1490,
  // Ссылка на оплату (QR/СБП) подключается после регистрации кассы.
  оплата: ''
};

window.Связь = (function () {
  'use strict';
  const Н = window.НАСТРОЙКИ;

  /** Обезличенное событие: регион, ниша, сумма, шаг. Без имён и контактов. */
  function событие(тип, данные) {
    if (!Н.endpoint) return Promise.resolve({ отправлено: false, причина: 'обработчик не подключён' });
    const тело = Object.assign({ тип, время: new Date().toISOString() }, данные || {});
    return отправить('/событие', тело).catch(() => ({ отправлено: false }));
  }

  /** Сообщение об ошибке в данных региона или в расчёте. */
  function замечание(текст, контекст) {
    const тело = {
      тип: 'замечание',
      текст: String(текст || '').slice(0, 4000),
      регион: (контекст && контекст.регион) || '',
      страница: location.href,
      время: new Date().toISOString()
    };
    if (!Н.endpoint) return Promise.resolve({ отправлено: false, запасной: телеграмСсылка(замечаниеТекстом(тело)) });
    return отправить('/замечание', тело);
  }

  /** Заявка на платную услугу. Контакт человек указывает сам и добровольно. */
  function заявка(данные) {
    const тело = Object.assign({ тип: 'заявка', время: new Date().toISOString() }, данные || {});
    if (!Н.endpoint) return Promise.resolve({ отправлено: false, запасной: телеграмСсылка(заявкаТекстом(тело)) });
    return отправить('/заявка', тело);
  }

  function отправить(путь, тело) {
    return fetch(Н.endpoint.replace(/\/$/, '') + путь, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(тело)
    }).then((r) => {
      if (!r.ok) throw new Error('HTTP ' + r.status);
      return { отправлено: true };
    });
  }

  function телеграмСсылка(текст) {
    return 'https://t.me/' + Н.телеграм + '?text=' + encodeURIComponent(текст);
  }

  function замечаниеТекстом(т) {
    return 'Нашёл неточность в калькуляторе соцконтракта.\nРегион: ' + (т.регион || 'не выбран') +
      '\nЧто не так: ' + т.текст;
  }

  function заявкаТекстом(т) {
    return 'Заявка на подготовку пакета по соцконтракту.\n' +
      'Регион: ' + (т.регион || '') + '\nНаправление: ' + (т.ниша || '') +
      '\nСумма по смете: ' + (т.сумма || '') + ' руб.\n' +
      (т.комментарий ? 'Комментарий: ' + т.комментарий + '\n' : '') +
      'Готов оплатить ' + Н.цена + ' руб.';
  }

  return { событие, замечание, заявка, телеграмСсылка, замечаниеТекстом, заявкаТекстом };
})();
