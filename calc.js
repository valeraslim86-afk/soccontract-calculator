/* Чистая расчётная логика калькулятора соцконтракта.
   Никакого DOM: эти функции покрыты тестами (tests/calc.test.js).
   Нормы: Правила ПП РФ от 16.11.2023 № 1931, ст. 8.1 ФЗ от 17.07.1999 № 178-ФЗ. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.Расчёт = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  // Предельные доли расходов от суммы помощи (п. 39-40 Правил № 1931).
  // Формулировки - по п. 10 подп. «б» абз. 2 Правил № 1931 (ред. ПП от 29.12.2025 № 2191).
  // ❗5 % - это продвижение именно на торговых площадках, в сервисах объявлений и соцсетях;
  // офлайн-реклама (вывеска, листовки) под этот лимит по букве нормы не подпадает.
  const ЛИМИТЫ = {
    разрешения: { доля: 0.10, имя: 'Разрешительные документы, ПО, электронная подпись' },
    аренда: { доля: 0.15, имя: 'Аренда и иные имущественные обязательства' },
    продвижение: { доля: 0.05, имя: 'Продвижение на площадках, в объявлениях и соцсетях' },
    основные: { доля: 1.00, имя: 'Оборудование и основные средства' },
    запасы: { доля: 1.00, имя: 'Сырьё, материалы, товарные запасы' }
  };
  const МАКСИМУМ = 350000;        // до 350 000 ₽ на своё дело (п. 4 «б» Правил)
  const МАКСИМУМ_ЛПХ = 200000;    // личное подсобное хозяйство (п. 4 «в»)
  const МАКСИМУМ_ОБУЧЕНИЕ = 30000; // обучение сверх суммы (п. 4)

  const округлить = (x) => Math.round((Number(x) || 0) * 100) / 100;
  // Числа в сообщениях человеку - с разделителями разрядов, как везде на странице.
  const рубли = (x) => Math.round(Number(x) || 0).toLocaleString('ru-RU');

  /** Среднедушевой доход семьи за 3 месяца и сравнение с ПМ региона (п. 3 Правил). */
  function доход(вход) {
    // ❗С 01.01.2026 (п. 3(1) Правил, введён ПП № 2191) участникам СВО и членам их семей
    // помощь оказывается БЕЗ оценки дохода - иначе им выдавался бы ложный отказ.
    const безОценкиДохода = !!вход.безОценкиДохода;
    const членов = Math.max(1, rint(вход.членовСемьи));
    const месяцы = [вход.доход1, вход.доход2, вход.доход3].map(num);
    const всего = месяцы.reduce((a, b) => a + b, 0);
    const среднедушевой = округлить(всего / 3 / членов);
    const пм = num(вход.пмДуша);
    const порог = округлить(пм * членов * 3);
    return {
      всегоЗаТриМесяца: округлить(всего),
      среднедушевой,
      пм,
      членов,
      безОценкиДохода,
      проходит: безОценкиДохода || (пм > 0 && среднедушевой < пм),
      запасДоПорога: округлить(порог - всего),   // на сколько доход ниже порога
      превышение: округлить(Math.max(0, среднедушевой - пм))
    };
  }

  /** Проверка сметы на лимиты Правил № 1931. Строки: {категория, название, сумма}. */
  function смета(строки, опции) {
    const о = опции || {};
    const максимум = num(о.максимум) || МАКСИМУМ;
    const чистые = (строки || [])
      .map((с) => ({ категория: с.категория, название: (с.название || '').trim(), сумма: num(с.сумма) }))
      .filter((с) => с.сумма > 0);

    const итого = округлить(чистые.reduce((a, с) => a + с.сумма, 0));
    const поКатегориям = {};
    Object.keys(ЛИМИТЫ).forEach((k) => { поКатегориям[k] = 0; });
    чистые.forEach((с) => {
      if (поКатегориям[с.категория] === undefined) поКатегориям[с.категория] = 0;
      поКатегориям[с.категория] += с.сумма;
    });

    // База для процентов - сумма запрашиваемой помощи (итог сметы, но не больше максимума).
    const база = Math.min(итого, максимум);
    const нарушения = [];
    Object.keys(ЛИМИТЫ).forEach((k) => {
      const л = ЛИМИТЫ[k];
      if (л.доля >= 1) return;
      const предел = округлить(база * л.доля);
      const факт = округлить(поКатегориям[k] || 0);
      if (факт > предел + 0.01) {
        нарушения.push({
          категория: k, имя: л.имя, факт, предел,
          превышение: округлить(факт - предел), доля: л.доля
        });
      }
    });
    if (итого > максимум) {
      нарушения.push({
        категория: 'итого', имя: 'Общая сумма помощи', факт: итого, предел: максимум,
        превышение: округлить(итого - максимум), доля: 1
      });
    }
    return {
      строки: чистые, итого, поКатегориям, база,
      пределы: пределы(база),
      нарушения, годится: нарушения.length === 0 && итого > 0
    };
  }

  function пределы(база) {
    const out = {};
    Object.keys(ЛИМИТЫ).forEach((k) => {
      out[k] = ЛИМИТЫ[k].доля >= 1 ? null : округлить(база * ЛИМИТЫ[k].доля);
    });
    return out;
  }

  /** Финансовая модель на 12 месяцев. */
  function финмодель(вход) {
    const цена = num(вход.цена);
    const клиентов = num(вход.клиентовВМесяц);
    const себестоимость = num(вход.себестоимостьЕдиницы);
    const постоянные = num(вход.постоянныеРасходы);
    const режим = вход.режим || 'НПД_физлица';
    const выходНаМощность = clamp(rint(вход.выходНаМощность) || 3, 1, 12);

    const ставка = { НПД_физлица: 0.04, НПД_юрлица: 0.06, УСН_доходы: 0.06 }[режим] ?? 0.04;

    const месяцы = [];
    let накопл = 0;
    let окупаемость = null;
    const вложения = num(вход.вложения);
    for (let м = 1; м <= 12; м++) {
      const загрузка = Math.min(1, м / выходНаМощность);
      const штук = округлить(клиентов * загрузка);
      const выручка = округлить(цена * штук);
      const перем = округлить(себестоимость * штук);
      const налог = округлить(выручка * ставка);
      const прибыль = округлить(выручка - перем - постоянные - налог);
      накопл = округлить(накопл + прибыль);
      if (окупаемость === null && накопл >= вложения && вложения > 0) окупаемость = м;
      месяцы.push({ месяц: м, штук, выручка, переменные: перем, постоянные, налог, прибыль, накопл });
    }
    const год = месяцы.reduce((a, м) => ({
      выручка: округлить(a.выручка + м.выручка),
      переменные: округлить(a.переменные + м.переменные),
      постоянные: округлить(a.постоянные + м.постоянные),
      налог: округлить(a.налог + м.налог),
      прибыль: округлить(a.прибыль + м.прибыль)
    }), { выручка: 0, переменные: 0, постоянные: 0, налог: 0, прибыль: 0 });

    const мощность = месяцы[11];
    const маржа = мощность.выручка > 0 ? округлить(мощность.прибыль / мощность.выручка * 100) : 0;
    const точкаБезубыточности = (цена - себестоимость - цена * ставка) > 0
      ? Math.ceil(постоянные / (цена - себестоимость - цена * ставка))
      : null;

    return { месяцы, год, окупаемостьМес: окупаемость, маржаНаМощности: маржа, точкаБезубыточности, ставкаНалога: ставка };
  }

  /** Сводная проверка готовности заявки. Возвращает список проблем и предупреждений. */
  function проверка(состояние) {
    const проблемы = [];
    const внимание = [];
    const д = состояние.доход;
    const с = состояние.смета;
    const ф = состояние.финмодель;

    if (!состояние.регион) проблемы.push('Не выбран регион - без него не с чем сравнивать доход.');
    if (д && !д.проходит && д.пм > 0 && !д.безОценкиДохода) {
      проблемы.push('Среднедушевой доход за 3 месяца (' + рубли(д.среднедушевой) +
        ' ₽) не ниже прожиточного минимума региона (' + рубли(д.пм) +
        ' ₽) - по п. 3 Правил № 1931 в помощи откажут.');
    }
    if (д && д.проходит && !д.безОценкиДохода && д.превышение === 0 && д.запасДоПорога < д.пм * 0.1) {
      внимание.push('Доход почти упирается в порог: любая забытая выплата или перевод может вывести семью за него.');
    }
    if (с) {
      с.нарушения.forEach((н) => {
        проблемы.push(н.категория === 'итого'
          ? 'Смета больше максимума: ' + рубли(н.факт) + ' ₽ при пределе ' + рубли(н.предел) + ' ₽.'
          : н.имя + ': ' + рубли(н.факт) + ' ₽ при пределе ' + рубли(н.предел) + ' ₽ (' +
            Math.round(н.доля * 100) + ' % суммы) - лишние ' + рубли(н.превышение) + ' ₽.');
      });
      if (с.итого > 0 && с.итого < МАКСИМУМ * 0.3) {
        внимание.push('Смета заметно меньше максимума - это нормально, комиссия смотрит на обоснованность, а не на «взять всё».');
      }
      const безОснов = (с.поКатегориям.основные || 0) + (с.поКатегориям.запасы || 0);
      if (с.итого > 0 && безОснов === 0) {
        внимание.push('В смете нет ни оборудования, ни материалов - комиссия почти наверняка спросит, на что тогда деньги.');
      }
    }
    if (ф) {
      if (ф.год.прибыль <= 0) проблемы.push('За первый год модель уходит в минус - защищать такой план нельзя, пересчитайте цену или объём.');
      if (ф.окупаемостьМес === null && ф.год.прибыль > 0) внимание.push('Вложения не окупаются за 12 месяцев - будьте готовы объяснить, почему это нормально для вашей ниши.');
      if (ф.маржаНаМощности > 70) внимание.push('Рентабельность выше 70 % выглядит нереалистично - комиссия воспринимает это как признак «нарисованного» плана.');
    }
    return { проблемы, внимание, годится: проблемы.length === 0 };
  }

  function num(x) { const v = parseFloat(String(x == null ? 0 : x).replace(/\s/g, '').replace(',', '.')); return isFinite(v) ? v : 0; }
  function rint(x) { const v = parseInt(x, 10); return isFinite(v) ? v : 0; }
  function clamp(v, a, b) { return Math.min(b, Math.max(a, v)); }

  return { ЛИМИТЫ, МАКСИМУМ, МАКСИМУМ_ЛПХ, МАКСИМУМ_ОБУЧЕНИЕ, доход, смета, пределы, финмодель, проверка, _num: num };
});
